function placement(steps,sc,name){
  if(steps===null) return {cat:"art"};
  const fails=checkStd(CHK[name],sc,scores&&scores.聽);
  if(fails.length) return {cat:"std",fails};
  for(let k=0;k<steps.length;k++){
    const {subs,t}=parseStep(steps[k]);
    const miss=subs.filter(x=>sc[x]===null);
    if(miss.length) return {cat:"miss",miss};
    const d=subs.reduce((s,x)=>s+sc[x],0)-t, m=d/subs.length;
    if(d>0) return {cat:(k===0&&m>=1)?"safe":"try",k,d};
    if(d<0) return {cat:m>=-1?"near":"hard",k,d};
  }
  return {cat:"try",tie:true};
}
