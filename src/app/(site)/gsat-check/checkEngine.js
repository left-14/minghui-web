function checkStd(code,sc,listen){
  if(!code) return [];
  const fails=[], need=k=>{const c=code[CHK_KEYS.indexOf(k)];return c==="-"?null:STD_IDX[c];};
  const ok=(k,i)=>sc[k]!==null&&sc[k]>=STD[k][i];
  const label=(k,i)=>`${SUBJ_NAMES[k]}需${STD_NAMES[i]}（${STD[k][i]}級分）`;
  ["國","英","社","自"].forEach(k=>{const i=need(k);if(i!==null&&!ok(k,i))fails.push(label(k,i));});
  const ia=need("數A"), ib=need("數B");
  if(ia!==null&&ib!==null){ if(!ok("數A",ia)&&!ok("數B",ib)) fails.push(label("數A",ia)+"或"+label("數B",ib)); }
  else if(ia!==null&&!ok("數A",ia)) fails.push(label("數A",ia));
  else if(ib!==null&&!ok("數B",ib)) fails.push(label("數B",ib));
  const L=code[6];
  if(L!=="-"&&(!listen||LISTEN_RANK[listen]<LISTEN_RANK[L])) fails.push(`英聽需${L}級`);
  return fails;
}
function placement(steps,sc,name){
  if(steps===null) return {cat:"art"};
  const fails=checkStd(CHK[name],sc,scores&&scores.聽);
  if(fails.length) return {cat:"std",fails};
  for(let k=0;k<steps.length;k++){
    const {subs,t}=parseStep(steps[k]);
    const miss=subs.filter(x=>sc[x]===null);
    if(miss.length) return {cat:"miss",miss};
    const d=subs.reduce((s,x)=>s+sc[x],0)-t, m=d/subs.length;
    if(d>0) return {cat:(k===0&&m>=1)?"safe":"try",k,d};
    if(d<0) return {cat:m>=-1?"near":"hard",k,d};
  }
  return {cat:"try",tie:true};
}
